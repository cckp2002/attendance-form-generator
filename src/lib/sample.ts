import { parsePeriods } from './periods';
import type { RawRecord } from './types';

/** 화면 체험용 가상 데이터 (실제 학생 정보가 아님). 연속 결석·조퇴·지각·결과와 별지가 생기는 경우를 모두 포함한다. */
export function sampleRecords(): RawRecord[] {
  const ALL = '조회,1교시,2교시,3교시,4교시,5교시,6교시,종례';
  let row = 1;
  const out: RawRecord[] = [];
  const add = (date: string, number: string, name: string, category: string, periods: string, reason: string) => {
    row++;
    out.push({
      id: `sample#${row}`, sourceFile: '예시 데이터', rowNo: row, grade: '1', classNo: '1',
      dateISO: date, dateRaw: date.replace(/-/g, '.') + '.', number, name, category,
      periodsRaw: periods, periods: parsePeriods(periods), reason,
    });
  };
  // 연속 결석 3일 (금→월 포함)
  add('2026-10-22', '3', '가상일', '질병결석', ALL, '독감');
  add('2026-10-23', '3', '가상일', '질병결석', ALL, '독감');
  add('2026-10-26', '3', '가상일', '질병결석', ALL, '독감');
  // 연속 조퇴 2일 (날짜마다 조퇴 교시가 다름)
  add('2026-10-21', '5', '가상이', '질병조퇴', '5교시,6교시,7교시,종례', '병원 진료');
  add('2026-10-22', '5', '가상이', '질병조퇴', '3교시,4교시,5교시,6교시,7교시,종례', '병원 진료');
  // 연속 조퇴 7일 (칸이 모자라 별지 생성)
  for (const d of ['2026-10-12', '2026-10-13', '2026-10-14', '2026-10-15', '2026-10-16', '2026-10-19', '2026-10-20']) {
    add(d, '8', '가상삼', '출석인정조퇴', '6교시,7교시,종례', '대회 준비');
  }
  // 연속 지각 3일 (등교 교시가 다름)
  add('2026-10-27', '12', '가상사', '미인정지각', '조회,1교시', '늦잠');
  add('2026-10-28', '12', '가상사', '미인정지각', '조회,1교시,2교시', '늦잠');
  add('2026-10-29', '12', '가상사', '미인정지각', '조회', '늦잠');
  // 연속 지각 5일 (별지 생성)
  for (const d of ['2026-11-02', '2026-11-03', '2026-11-04', '2026-11-05', '2026-11-06']) {
    add(d, '15', '가상오', '질병지각', '조회,1교시', '통원 치료');
  }
  // 연속 결과 2일 (교시가 떨어져 있음)
  add('2026-10-19', '20', '가상육', '미인정결과', '1교시,3교시,5교시', '무단 이탈');
  add('2026-10-20', '20', '가상육', '미인정결과', '2교시,3교시,4교시,7교시', '무단 이탈');
  return out;
}
